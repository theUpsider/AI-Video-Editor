"""Deterministic synthetic media with ground-truth manifests (clearly labeled synthetic).

Fixture media is produced from a :class:`FixtureSpec` with FFmpeg ``lavfi`` drawing (video) and
NumPy synthesis (audio). Generation code is independent of the renderer and the compiler: it never
imports :mod:`ave.render` or :mod:`ave.domain`, so expected values derived from a manifest stay an
independent oracle.

Video frames show a source-specific background color, the frame-index barcode of
:mod:`ave.fixtures.barcode`, and a one-frame full-white background flash on every event frame.
Audio carries a low-level pilot tone (source identification), a broadband chirp starting exactly at
every event time (sync and timing evidence), an overall gain and optional seeded white noise.

Results are cached under ``var/fixtures/<name>-<hash>/`` where the hash covers the specification,
the generator version and the FFmpeg version; a cache entry is reused only when its file still
matches the recorded SHA-256. Each entry holds the media file and ``manifest.json``.
"""

