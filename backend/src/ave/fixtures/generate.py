GENERATOR_VERSION = 1
SYNTHETIC_LABEL = "SYNTHETIC TEST FIXTURE generated by ave.fixtures - not user footage"

CHIRP_DURATION_S = 0.012
CHIRP_F0_HZ = 500.0
CHIRP_F1_HZ = 7000.0

VFR_TICK_RATE = 120
"""Time base (ticks per second) of variable-frame-rate fixtures."""

_TIMEOUT_S = 900.0


@functools.cache
def generator_digest() -> str:
    """Digest of the generator's own source files.

    It is part of every cache key, so an edited generator writes new files and a test never passes
    on the files an earlier generator left in the cache.
    """
    package = Path(__file__).resolve().parent
    digest = hashlib.sha256()
    for name in ("barcode.py", "generate.py", "standard.py"):
        digest.update((package / name).read_bytes())
    return digest.hexdigest()[:16]


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class AudioSpec(_Frozen):
    """One synthetic audio stream."""

    sample_rate: int = Field(ge=8000, le=192000)
    channels: int = Field(default=1, ge=1, le=8)
    pilot_hz: float = Field(gt=0)
    pilot_amplitude: float = Field(default=0.05, ge=0, le=1)
    event_amplitude: float = Field(default=0.5, ge=0, le=1)
    gain: float = Field(default=1.0, gt=0, le=4)
    noise_rms: float = Field(default=0.0, ge=0, le=1)
    seed: int = 0
    codec: Literal["aac", "pcm_s16le"] = "aac"


class VideoSpec(_Frozen):
    """The synthetic video stream."""

    width: int = Field(ge=16, le=8192)
    height: int = Field(ge=16, le=8192)
    fps: PositiveRational
    """Nominal rate; for VFR fixtures the frames are re-timed with :func:`vfr_frame_ticks`."""
    color: tuple[int, int, int]
    """Background RGB (identifies the source)."""
    rotation: int = 0
    """Display-matrix rotation written as metadata (the pixels are not rotated)."""
    sar: PositiveRational = Fraction(1)
    vfr: bool = False


class FixtureSpec(_Frozen):
    """Everything that determines one fixture file."""

    name: str = Field(pattern=r"^[a-z0-9][a-z0-9_-]*$")
    description: str
    duration: PositiveRational
    container: Literal["mp4", "m4a", "png"] = "mp4"
    video: VideoSpec | None = None
    audio: tuple[AudioSpec, ...] = ()
    events: tuple[Rational, ...] = ()
    """Event times in source seconds: a flash frame and a chirp onset at each."""

    @model_validator(mode="after")
    def _consistent(self) -> FixtureSpec:
        if self.video is None and not self.audio:
            raise ValueError("a fixture needs video or audio")
        if self.container == "png" and (self.video is None or self.audio):
            raise ValueError("png fixtures hold exactly one picture")
        if self.container == "m4a" and self.video is not None:
            raise ValueError("m4a fixtures are audio-only")
        for event in self.events:
            if not 0 <= event < self.duration:
                raise ValueError(f"event {event} outside [0, {self.duration})")
            if self.video is not None and not self.video.vfr and (event * self.video.fps) % 1:
                raise ValueError(f"event {event} is not on the video frame grid")
            for audio in self.audio:
                if (event * audio.sample_rate) % 1:
                    raise ValueError(f"event {event} is not on the {audio.sample_rate} Hz grid")
        return self

    def cache_key(self) -> str:
        """Hash of the specification, the generator (version and sources) and the FFmpeg version."""
        payload = json.dumps(
            {
                "spec": self.model_dump(mode="json"),
                "generator": GENERATOR_VERSION,
                "sources": generator_digest(),
                "ffmpeg": ffmpeg_version(),
            },
            sort_keys=True,
        )
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


@dataclass(frozen=True)
class Fixture:
    """A generated fixture file and its ground-truth manifest."""

    spec: FixtureSpec
    path: Path
    sha256: str
    manifest: dict[str, Any]


# --------------------------------------------------------------------------------------------
# Signal definitions (shared with test oracles through the manifest parameters)
# --------------------------------------------------------------------------------------------


def chirp(sample_rate: int) -> npt.NDArray[np.float64]:
    """Unit-amplitude Hann-windowed linear chirp (500 Hz to 7 kHz over 12 ms)."""
    count = round(CHIRP_DURATION_S * sample_rate)
    t = np.arange(count) / sample_rate
    sweep = (CHIRP_F1_HZ - CHIRP_F0_HZ) / (2 * CHIRP_DURATION_S)
    window = np.sin(np.pi * np.arange(count) / count) ** 2
    result: npt.NDArray[np.float64] = window * np.sin(2 * np.pi * (CHIRP_F0_HZ * t + sweep * t * t))
    return result


def synthesize_audio(
    spec: AudioSpec, duration: Fraction, events: tuple[Fraction, ...]
) -> npt.NDArray[np.float32]:
    """Samples ``(n, channels)`` float32: gain * (pilot + chirps) + seeded white noise."""
    count = math.ceil(duration * spec.sample_rate)
    t = np.arange(count, dtype=np.float64) / spec.sample_rate
    signal = spec.pilot_amplitude * np.sin(2 * np.pi * spec.pilot_hz * t)
    burst = spec.event_amplitude * chirp(spec.sample_rate)
    for event in events:
        start = int(event * spec.sample_rate)
        end = min(count, start + len(burst))
        signal[start:end] += burst[: end - start]
    signal *= spec.gain
    if spec.noise_rms > 0:
        signal += spec.noise_rms * np.random.default_rng(spec.seed).standard_normal(count)
    mono = signal.astype(np.float32)
    samples: npt.NDArray[np.float32] = np.repeat(mono[:, None], spec.channels, axis=1)
    return samples


def vfr_frame_ticks(duration: Fraction) -> list[int]:
    """PTS (in 1/120 s ticks) of a deterministic irregular frame sequence covering ``duration``.

    Frame 0 is at 0; frame ``n`` follows frame ``n - 1`` after ``1 + ((7 n^2 + 3 n) mod 5)`` ticks,
    so frame intervals vary between 1/120 s and 5/120 s without a short period.
    """
    limit = duration * VFR_TICK_RATE
    ticks = [0]
    n = 1
    while True:
        nxt = ticks[-1] + 1 + (7 * n * n + 3 * n) % 5
        if nxt >= limit:
            return ticks
        ticks.append(nxt)
        n += 1


