def _hex(color: tuple[int, int, int]) -> str:
    return "0x" + "".join(f"{max(0, min(255, c)):02X}" for c in color)


def _video_graph(spec: FixtureSpec, video: VideoSpec) -> tuple[str, int | None]:
    """Filter script drawing the fixture video; returns ``(script, vfr_frame_count)``."""
    layout = barcode_layout(video.width, video.height)
    rate = f"{video.fps.numerator}/{video.fps.denominator}"
    vfr_ticks = vfr_frame_ticks(spec.duration) if video.vfr else None
    source_rate = str(VFR_TICK_RATE) if video.vfr else rate
    parts = [
        f"color=c={_hex(video.color)}:s={video.width}x{video.height}:r={source_rate}:"
        f"d={float(spec.duration) + 1}",
        "format=rgb24",
    ]
    if spec.events:
        if vfr_ticks is not None:
            flash_frames = [
                i
                for i, tick in enumerate(vfr_ticks)
                if Fraction(tick, VFR_TICK_RATE) in spec.events
            ]
        else:
            flash_frames = [int(event * video.fps) for event in spec.events]
        if flash_frames:
            condition = "+".join(f"eq(n,{frame})" for frame in flash_frames)
            parts.append(f"drawbox=x=0:y=0:w=iw:h=ih:color=white:t=fill:enable='{condition}'")
    parts.append(
        f"drawbox=x={layout.x0}:y={layout.y0}:w={layout.grid_size}:h={layout.grid_size}:"
        "color=black:t=fill"
    )
    for cell in range(CELLS):
        x, y, width, height = layout.cell_rect(cell)
        parts.append(
            f"drawbox=x={x}:y={y}:w={width}:h={height}:color=white:t=fill:"
            f"enable='{ffmpeg_bit_expression(cell)}'"
        )
    if video.sar != 1:
        parts.append(f"setsar={video.sar.numerator}/{video.sar.denominator}")
    if vfr_ticks is not None:
        parts.append(f"trim=end_frame={len(vfr_ticks)}")
        parts.append(f"settb=1/{VFR_TICK_RATE}")
        parts.append("setpts=if(eq(N\\,0)\\,0\\,PREV_OUTPTS+1+mod(7*N*N+3*N\\,5))")
    else:
        frames = math.ceil(spec.duration * video.fps)
        parts.append(f"trim=end_frame={frames}")
    if spec.container == "png":
        parts.append("trim=end_frame=1")
    else:
        parts.append("scale=out_color_matrix=bt709:out_range=tv")
        parts.append("format=yuv420p")
    return ",".join(parts) + "[vout]\n", (len(vfr_ticks) if vfr_ticks is not None else None)


def _encode(spec: FixtureSpec, work: Path, output: Path) -> dict[str, Any]:
    args = ["-hide_banner", "-nostdin", "-v", "error", "-y"]
    extra: dict[str, Any] = {}
    inputs = 0
    if spec.video is not None:
        script, vfr_frames = _video_graph(spec, spec.video)
        script_path = work / "video.filter"
        script_path.write_text(script, encoding="utf-8")
        args += ["-filter_complex_script", str(script_path)]
        if vfr_frames is not None:
            extra["vfr_frame_ticks"] = vfr_frame_ticks(spec.duration)
            extra["vfr_tick_rate"] = VFR_TICK_RATE
    for index, audio in enumerate(spec.audio):
        raw = work / f"audio{index}.f32"
        synthesize_audio(audio, spec.duration, spec.events).tofile(raw)
        args += [
            "-f", "f32le", "-ar", str(audio.sample_rate), "-ac", str(audio.channels),
            "-i", media_url(raw),
        ]  # fmt: skip
        inputs += 1
    if spec.video is not None:
        args += ["-map", "[vout]"]
    for index in range(inputs):
        args += ["-map", f"{index}:a:0"]
    if spec.container == "png":
        args += ["-frames:v", "1", "-f", "image2", "-c:v", "png", media_url(output)]
        run_tool("ffmpeg", args, timeout=_TIMEOUT_S)
        return extra
    if spec.video is not None:
        video = spec.video
        gop = max(1, round(video.fps))
        args += [
            "-c:v", "libx264", "-preset", "veryfast", "-crf", "12", "-g", str(gop),
            "-pix_fmt", "yuv420p", "-color_primaries", "bt709", "-color_trc", "bt709",
            "-colorspace", "bt709", "-color_range", "tv",
        ]  # fmt: skip
        if video.vfr:
            args += ["-fps_mode", "passthrough", "-video_track_timescale", str(VFR_TICK_RATE)]
    for index, audio in enumerate(spec.audio):
        if audio.codec == "aac":
            args += [f"-c:a:{index}", "aac", f"-b:a:{index}", "256k"]
        else:
            args += [f"-c:a:{index}", "pcm_s16le"]
    container = "mp4" if spec.container == "mp4" else "ipod"
    if spec.video is not None and spec.video.rotation:
        staged = work / f"unrotated.{spec.container}"
        run_tool("ffmpeg", [*args, "-f", container, media_url(staged)], timeout=_TIMEOUT_S)
        run_tool(
            "ffmpeg",
            [
                "-hide_banner", "-nostdin", "-v", "error", "-y",
                "-display_rotation", str(spec.video.rotation), "-i", media_url(staged),
                "-map", "0", "-c", "copy", "-f", container, media_url(output),
            ],
            timeout=_TIMEOUT_S,
        )  # fmt: skip
    else:
        run_tool("ffmpeg", [*args, "-f", container, media_url(output)], timeout=_TIMEOUT_S)
    return extra


def _manifest(
    spec: FixtureSpec, file_name: str, checksum: str, extra: dict[str, Any]
) -> dict[str, Any]:
    manifest: dict[str, Any] = {
        "synthetic": True,
        "label": SYNTHETIC_LABEL,
        "generator_version": GENERATOR_VERSION,
        "ffmpeg": ffmpeg_version(),
        "file": file_name,
        "sha256": checksum,
        "spec": spec.model_dump(mode="json"),
        "chirp": {
            "duration_s": CHIRP_DURATION_S,
            "f0_hz": CHIRP_F0_HZ,
            "f1_hz": CHIRP_F1_HZ,
            "window": "hann",
            "onset": "event time is the first chirp sample",
        },
        "events": [rational_to_json(Fraction(e)) for e in spec.events],
        **extra,
    }
    if spec.video is not None:
        layout = barcode_layout(spec.video.width, spec.video.height)
        manifest["barcode"] = {
            "cell": layout.cell,
            "x0": layout.x0,
            "y0": layout.y0,
            "patch": [layout.patch_x, layout.patch_y, layout.patch_size],
        }
    return manifest


def _load_cached(directory: Path, spec: FixtureSpec) -> Fixture | None:
    manifest_path = directory / "manifest.json"
    if not manifest_path.is_file():
        return None
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    path = directory / str(manifest.get("file", ""))
    if not path.is_file() or sha256_file(path) != manifest.get("sha256"):
        return None
    return Fixture(spec=spec, path=path, sha256=str(manifest["sha256"]), manifest=manifest)


def ensure_fixture(spec: FixtureSpec, root: Path | None = None) -> Fixture:
    """Returns the cached fixture for ``spec``, generating it first when needed."""
    base = root or fixtures_root()
    directory = base / f"{spec.name}-{spec.cache_key()}"
    cached = _load_cached(directory, spec)
    if cached is not None:
        return cached
    work = base / f".{spec.name}.tmp-{uuid.uuid4().hex}"
    work.mkdir(parents=True)
    try:
        file_name = f"{spec.name}.{spec.container}"
        extra = _encode(spec, work, work / file_name)
        checksum = sha256_file(work / file_name)
        manifest = _manifest(spec, file_name, checksum, extra)
        (work / "manifest.json").write_text(
            json.dumps(manifest, indent=2, sort_keys=True), encoding="utf-8"
        )
        for leftover in work.iterdir():
            if leftover.name not in {file_name, "manifest.json"}:
                leftover.unlink()
        if directory.exists():
            shutil.rmtree(directory)
        work.rename(directory)
    finally:
        if work.exists():
            shutil.rmtree(work, ignore_errors=True)
    fixture = _load_cached(directory, spec)
    if fixture is None:  # pragma: no cover - only on concurrent deletion
        raise RuntimeError(f"fixture {spec.name} vanished after generation")
    return fixture
